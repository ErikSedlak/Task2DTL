def make_pgm(arr: np.ndarray) -> bytes:
    h, w = arr.shape
    return f"P5\n# Generated by test\n{w} {h}\n65535\n".encode() + arr.astype(">u2").tobytes()


def test_pgm_big_endian_and_comment():
    a = np.array([[0, 1331, 65535], [256, 1, 2]], dtype=np.uint16)
    np.testing.assert_array_equal(read_pgm16(make_pgm(a)), a)


def _write_seq_files(put):
    put("_info.txt", INFO.encode())
    for i in range(2):
        d = np.full((3, 4), 1000 * (i + 1), dtype=np.uint16)
        d[0, 0] = 0
        put(f"frame-{i:06d}.depth.pgm", make_pgm(d))
        T = np.eye(4)
        T[0, 3] = i
        put(f"frame-{i:06d}.pose.txt", "\n".join(" ".join(map(str, r)) for r in T).encode())


def test_sequence_zip_and_folder_agree(tmp_path):
    zdir, fdir = tmp_path / "z", tmp_path / "f"
    zdir.mkdir()
    (fdir / "sequence").mkdir(parents=True)
    with zipfile.ZipFile(zdir / "sequence.zip", "w") as z:
        _write_seq_files(lambda n, b: z.writestr(n, b))
    _write_seq_files(lambda n, b: (fdir / "sequence" / n).write_bytes(b))
    with SequenceReader(zdir) as sz, SequenceReader(fdir) as sf:
        assert (sz.source, sf.source) == ("zip", "folder")
        assert sz.frame_ids == sf.frame_ids == [0, 1]
        assert sz.info.depth_wh == (4, 3)
        np.testing.assert_allclose(sz.info.K_depth[0, 0], 176.594)
        fz, ff = list(iter_frames(sz)), list(iter_frames(sf))
        for a, b in zip(fz, ff):
            np.testing.assert_array_equal(a.depth, b.depth)
            np.testing.assert_array_equal(a.pose_c2w, b.pose_c2w)
        assert fz[1].depth[1, 1] == np.float32(2.0)  # mm / 1000
        assert fz[1].depth[0, 0] == 0.0  # invalid stays 0
        assert fz[1].pose_c2w[0, 3] == 1.0


def test_meta_both_rigid_forms():
    T = np.eye(4)
    T[:3, 3] = [1.0, 2.0, 3.0]
    colmajor = T.T.reshape(-1).tolist()
    meta = parse_meta(
        [
            {
                "reference": "R",
                "type": "train",
                "scans": [
                    {
                        "reference": "S1",
                        "transform": colmajor,
                        "rigid": [
                            {"instance_reference": 5, "instance_rescan": 5, "transform": colmajor},
                            7,
                        ],
                        "removed": [9],
                        "nonrigid": [],
                    },
                    {"reference": "S2"},  # no transform -> identity
                ],
            }
        ]
    )
    assert meta["R"].is_reference
    s1 = meta["S1"]
    np.testing.assert_array_equal(s1.T_align[:3, 3], [1, 2, 3])
    assert [r.id for r in s1.rigid] == [5, 7]
    assert s1.rigid[0].T is not None and s1.rigid[1].T is None
    assert s1.removed == [9]
    np.testing.assert_array_equal(meta["S2"].T_align, np.eye(4))


def test_face_majority():
    lab = np.array([1, 1, 2, 3])
    faces = np.array([[0, 1, 2], [2, 3, 1], [2, 0, 1], [0, 2, 2]])
    # [1,1,2]->1, [2,3,1] all differ -> vertex 0 = 2, [2,1,1]->1, [1,2,2]->2
    np.testing.assert_array_equal(face_majority(lab, faces), [1, 2, 1, 2])


