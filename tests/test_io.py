def test_load_scan_synthetic(tmp_path):
    d = tmp_path / "scanA"
    d.mkdir()
    (d / "labels.instances.annotated.v2.ply").write_text(PLY)
    (d / "semseg.v2.json").write_text(
        json.dumps({"segGroups": [{"objectId": 7, "label": "chair"}]})
    )
    sc = load_scan(tmp_path, "scanA")
    assert sc.vertices.shape == (4, 3) and sc.faces.shape == (2, 3)
    assert set(sc.instances) == {7}  # objectId 0 = unlabelled, not an instance
    inst = sc.instances[7]
    assert inst.label == "chair" and inst.nyu40 == 5 and inst.n_vertices == 3
    np.testing.assert_allclose(inst.centroid, [1 / 3, 1 / 3, 0])
    np.testing.assert_array_equal(sc.face_labels, [7, 7])
    assert sc.intrinsics is None


def test_dssg(tmp_path):
    (tmp_path / "3DSSG").mkdir()
    objs = {"scans": [{"scan": "A", "objects": [{"id": "3", "label": "cup", "nyu40": "40"}]}]}
    rels = {
        "scans": [
            {"scan": "A", "relationships": [[3, 1, 15, "standing on"], [3, 1, 15, "standing on"]]}
        ]
    }
    (tmp_path / "3DSSG" / "objects.json").write_text(json.dumps(objs))
    (tmp_path / "3DSSG" / "relationships.json").write_text(json.dumps(rels))
    assert load_objects(tmp_path, "A") == {3: {"id": "3", "label": "cup", "nyu40": 40}}
    assert load_relations(tmp_path, "A") == [(3, 1, "standing on")]
    assert load_objects(tmp_path, "missing") == {}


def test_read_pairs(tmp_path):
    p = tmp_path / "pairs.txt"
    p.write_text("# reference_scan rescan\nA B\n\nC D  # comment\n")
    assert read_pairs(p) == [("A", "B"), ("C", "D")]
